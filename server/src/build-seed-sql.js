/**
 * build-seed-sql.js
 * Reads data/fakkir-data.json and writes:
 *   - server/sql/seed.sql               (one file; for psql / Node)
 *   - server/sql/seed-parts/seed-NN.sql (smaller numbered chunks for the Supabase SQL Editor)
 *
 * The Supabase SQL Editor rejects very large queries ("Query is too large"), so paste the
 * numbered part files one at a time, in order. Each part is its own transaction, re-declares
 * the categories (needed for the questions foreign key) and upserts, so it is safe to re-run.
 * Part 01 also clears previous data (delete) so versions A–O fully replace it.
 *
 * Multi-row INSERT ... VALUES (...),(...) ... is used to keep files small.
 *
 * Usage:  node src/build-seed-sql.js
 */
const fs = require('fs');
const path = require('path');

const dataPath = path.join(__dirname, '../../data/fakkir-data.json');
const outPath = path.join(__dirname, '../sql/seed.sql');
const partsDir = path.join(__dirname, '../sql/seed-parts');
const CHUNK = 250; // questions per part file

const data = JSON.parse(fs.readFileSync(dataPath, 'utf8'));

// --- SQL literal helpers ---
const q = (v) => {
  if (v === null || v === undefined || v === '') return 'NULL';
  return `'${String(v).replace(/'/g, "''")}'`;
};
const num = (v) => (v === null || v === undefined || v === '' ? 'NULL' : Number(v));
const jsonb = (v) => {
  if (v === null || v === undefined) return 'NULL';
  return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
};

// --- row tuples ---
const catTuples = data.categories.map((c, i) =>
  `(${q(c.slug)},${q(c.name)},${q(c.color || 'blue')},${q(c.image)},${i})`
);
const flagTuples = Object.entries(data.flags || {}).map(([key, image]) => `(${q(key)},${q(image)})`);
const qTuples = data.questions.map((it) =>
  `(${q(it.category)},${num(it.version) || 1},${num(it.ord) || 0},${num(it.value) || 0},` +
  `${q(it.type || 'normal')},${q(it.q)},${q(it.a)},${q(it.note)},${q(it.flag)},` +
  `${jsonb(it.clues)},${num(it.num)},${q(it.evidence)},${jsonb(it.suspects)},${q(it.image)})`
);

// --- multi-row upsert statements ---
const CAT_HEAD = 'insert into categories(slug,name,color,image,sort_order) values';
const CAT_TAIL = 'on conflict(slug) do update set name=excluded.name,color=excluded.color,image=excluded.image,sort_order=excluded.sort_order;';
const FLAG_HEAD = 'insert into flags(key,image) values';
const FLAG_TAIL = 'on conflict(key) do update set image=excluded.image;';
const Q_HEAD = 'insert into questions(category,version,ord,value,type,q,a,note,flag,clues,num,evidence,suspects,image) values';
const Q_TAIL = 'on conflict(category,version,ord) do update set value=excluded.value,type=excluded.type,' +
  'q=excluded.q,a=excluded.a,note=excluded.note,flag=excluded.flag,clues=excluded.clues,' +
  'num=excluded.num,evidence=excluded.evidence,suspects=excluded.suspects,image=excluded.image;';

const upsert = (head, tuples, tail) => head + '\n' + tuples.join(',\n') + '\n' + tail;

const catStmt = upsert(CAT_HEAD, catTuples, CAT_TAIL);
const flagStmt = flagTuples.length ? upsert(FLAG_HEAD, flagTuples, FLAG_TAIL) : null;

// --- 1) full single file (psql / node) ---
const full = [
  '-- FAKKIR seed data. Generated by build-seed-sql.js. Do not edit by hand.',
  '-- Run server/sql/schema.sql first. For the Supabase SQL Editor use server/sql/seed-parts/ (this file is large).',
  'begin;',
  '',
  '-- Replace all game content: versions A–O fully replace any previous data.',
  'delete from questions;',
  'delete from flags;',
  '',
  catStmt,
  ...(flagStmt ? ['', flagStmt] : []),
  '',
  upsert(Q_HEAD, qTuples, Q_TAIL),
  '',
  'commit;',
  ''
];
fs.writeFileSync(outPath, full.join('\n'), 'utf8');

// --- 2) chunked part files for the Supabase SQL Editor ---
fs.rmSync(partsDir, { recursive: true, force: true });
fs.mkdirSync(partsDir, { recursive: true });

const chunks = [];
for (let i = 0; i < qTuples.length; i += CHUNK) chunks.push(qTuples.slice(i, i + CHUNK));
const total = chunks.length;
const pad = (n) => String(n).padStart(2, '0');

chunks.forEach((chunk, idx) => {
  const partNo = idx + 1;
  const isFirst = partNo === 1;
  const lines = [
    `-- FAKKIR seed — part ${partNo} of ${total}. Generated; do not edit by hand.`,
    '-- Run server/sql/schema.sql once, then paste these part files into the Supabase SQL Editor in order (01, 02, ...).',
    'begin;',
    ''
  ];
  if (isFirst) {
    lines.push('-- Replace all game content: versions A–O fully replace any previous data.');
    lines.push('delete from questions;');
    lines.push('delete from flags;');
    lines.push('');
  }
  // categories repeated in every part so the questions foreign key always resolves
  lines.push('-- Categories (idempotent; required by the questions foreign key)');
  lines.push(catStmt);
  if (isFirst && flagStmt) { lines.push('', flagStmt); }
  lines.push('');
  lines.push(`-- Questions ${idx * CHUNK + 1}..${idx * CHUNK + chunk.length}`);
  lines.push(upsert(Q_HEAD, chunk, Q_TAIL));
  lines.push('');
  lines.push('commit;');
  lines.push('');
  fs.writeFileSync(path.join(partsDir, `seed-${pad(partNo)}.sql`), lines.join('\n'), 'utf8');
});

const versions = [...new Set(data.questions.map((x) => x.version))].sort((a, b) => a - b);
console.log(`Wrote ${outPath}`);
console.log(`Wrote ${total} part files to ${partsDir} (seed-01.sql .. seed-${pad(total)}.sql, ${CHUNK} questions each)`);
console.log(
  `  ${data.categories.length} categories, ${Object.keys(data.flags || {}).length} flags, ` +
  `${data.questions.length} questions (versions: ${versions.join(', ')}).`
);
